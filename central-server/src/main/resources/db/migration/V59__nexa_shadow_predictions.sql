-- NEXA(P09-T009) shadow 예측 persistence — additive only.
-- 기존 마이그레이션(V1~V58)은 건드리지 않는다(깨끗한 새 DB·기존 V58 DB 모두에 적용 가능). 운영 DB 적용 금지.
-- H2(PostgreSQL 모드)·Postgres 공통 SQL.
--
-- 경계 규칙(logging-boundary.md, ADR 0007): 원문 메시지/프롬프트/모델 응답 본문/snowflake 원문을 담지 않는다.
-- feature 원시 값 대신 feature HASH 만 저장한다. Discord 식별자는 가명 토큰만.
--
-- shadow = 미발화 관찰: 이 표의 예측은 절대 실제 전송되지 않았다(T008 hard block). 정책별 분포·샘플·예상 발사
-- 시점만 기록해 같은 장면에서 여러 baseline 을 나란히 비교한다(acceptance T009).

CREATE TABLE nexa_shadow_prediction (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 장면 키(여러 정책 예측의 비교 join 축). 가명/원시 String.
    guild_pseudonym        VARCHAR(128) NOT NULL,
    channel_id             VARCHAR(64)  NOT NULL,
    scene_seq              BIGINT       NOT NULL,
    -- 정책 무효화 추적 context 버전(재현 키).
    context_version        BIGINT       NOT NULL DEFAULT 0,
    -- 이 예측을 낸 정책/모델 버전(AlwaysSilent/Mention/FixedProb/Cooldown/BurstAware/legacy 식별).
    model_version          VARCHAR(96)  NOT NULL,
    -- 예측 분포: action kind→확률 직렬화(콤마 구분 "code:prob"). 정책별 발화/침묵 성향 비교의 핵심.
    action_weights         VARCHAR(512) NOT NULL,
    -- seed 로 접은 단일 샘플 행동(안정 코드 ignore/wait/react/speak/cancel_pending).
    sampled_action         VARCHAR(24)  NOT NULL,
    -- 예상 발사 시각(샘플 delay 적용). NEVER/IGNORE 면 NULL(발사 안 함).
    expected_fire_at       TIMESTAMP    NULL,
    -- 결정론 seed(재현 키).
    seed                   BIGINT       NOT NULL,
    -- 근거 feature 벡터 HASH(원본 feature 비저장 — 재현/diff 용).
    feature_hash           VARCHAR(128) NOT NULL,
    feature_vector_version INTEGER      NOT NULL,
    -- 예측 생성 시각(보존/수집 기간 기준).
    predicted_at           TIMESTAMP    NOT NULL,
    -- 같은 (장면, 정책) 재기록은 멱등(결정론 — 한 정책의 한 장면 예측은 하나).
    CONSTRAINT uk_nexa_shadow_prediction_scene_model
        UNIQUE (guild_pseudonym, channel_id, scene_seq, model_version)
);

-- 한 장면의 모든 정책 예측 조회(여러 baseline 비교 — acceptance T009).
CREATE INDEX idx_nexa_shadow_prediction_scene
    ON nexa_shadow_prediction(guild_pseudonym, channel_id, scene_seq);
-- 길드별 수집량·오류율 집계(T010 API)·보존 purge.
CREATE INDEX idx_nexa_shadow_prediction_guild_time
    ON nexa_shadow_prediction(guild_pseudonym, predicted_at);
