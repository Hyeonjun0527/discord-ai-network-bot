SELECT ca.id,
       1,
       'general_assistant',
       'friendly',
       'balanced',
       '민감정보(비밀번호·API 키·개인정보)는 입력하지 않도록 안내하고, 확실하지 않은 내용은 단정하지 않습니다.',
