CREATE TABLE channel_ai (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id                   BIGINT NOT NULL,
    channel_id                 BIGINT NOT NULL,
    display_name               VARCHAR(80) NOT NULL,
    avatar_url                 VARCHAR(512),
    active_behavior_version_id BIGINT,
    source                     VARCHAR(64) NOT NULL DEFAULT 'manual',
    created_at                 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                 TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_channel_ai_channel UNIQUE (guild_id, channel_id)
);
CREATE INDEX idx_channel_ai_channel ON channel_ai(guild_id, channel_id);

CREATE TABLE ai_behavior_version (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_ai_id  BIGINT NOT NULL,
    version        INT NOT NULL,
    purpose        VARCHAR(200) NOT NULL DEFAULT 'general_assistant',
    tone           VARCHAR(80) NOT NULL DEFAULT 'friendly',
    answer_length  VARCHAR(40) NOT NULL DEFAULT 'balanced',
    constitution   VARCHAR(2000),
    safety_level   VARCHAR(40) NOT NULL DEFAULT 'standard',
    created_by     BIGINT,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    change_summary VARCHAR(500),
    CONSTRAINT fk_ai_behavior_version_channel_ai FOREIGN KEY (channel_ai_id) REFERENCES channel_ai(id) ON DELETE CASCADE,
    CONSTRAINT uk_ai_behavior_version UNIQUE (channel_ai_id, version)
);
CREATE INDEX idx_ai_behavior_version_channel ON ai_behavior_version(channel_ai_id, version DESC);

CREATE TABLE ai_change_proposal (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id              BIGINT NOT NULL,
    channel_id            BIGINT NOT NULL,
    channel_ai_id         BIGINT,
    proposed_behavior_id  BIGINT,
    status                VARCHAR(40) NOT NULL DEFAULT 'approved',
    requested_by          BIGINT,
    reviewed_by           BIGINT,
    reason                VARCHAR(500),
    created_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at           TIMESTAMP,
    CONSTRAINT fk_ai_change_proposal_channel_ai FOREIGN KEY (channel_ai_id) REFERENCES channel_ai(id) ON DELETE SET NULL,
    CONSTRAINT fk_ai_change_proposal_behavior FOREIGN KEY (proposed_behavior_id) REFERENCES ai_behavior_version(id) ON DELETE SET NULL
);
CREATE INDEX idx_ai_change_proposal_scope ON ai_change_proposal(guild_id, channel_id, created_at DESC);

CREATE TABLE customization_audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id     BIGINT NOT NULL,
    channel_id   BIGINT NOT NULL,
    actor_id     BIGINT,
    action       VARCHAR(80) NOT NULL,
    target_type  VARCHAR(80) NOT NULL,
    target_id    BIGINT,
    summary      VARCHAR(1000),
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_customization_audit_scope ON customization_audit_log(guild_id, channel_id, created_at DESC);

