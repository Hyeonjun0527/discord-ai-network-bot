CREATE TABLE ai_network_profile (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id              BIGINT NOT NULL,
    display_name          VARCHAR(80) NOT NULL DEFAULT '냥시스턴트 네트워크',
    tagline               VARCHAR(160) NOT NULL DEFAULT '함께 만드는 AI 네트워크',
    description           VARCHAR(1000),
    default_safety_notice VARCHAR(500),
    network_level         INT NOT NULL DEFAULT 1,
    created_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_ai_network_profile_guild UNIQUE (guild_id)
);
CREATE INDEX idx_ai_network_profile_guild ON ai_network_profile(guild_id);

CREATE TABLE provider_capability_profile (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id              BIGINT NOT NULL,
    provider_user_id      BIGINT NOT NULL,
    provider_state        VARCHAR(40) NOT NULL DEFAULT 'UNKNOWN',
    model_count           INT NOT NULL DEFAULT 0,
    model_names           VARCHAR(2000),
    capability_tags       VARCHAR(1000),
    quality_tier          VARCHAR(40) NOT NULL DEFAULT 'unknown',
    max_burden            VARCHAR(40) NOT NULL DEFAULT 'LIGHT',
    max_concurrency       INT NOT NULL DEFAULT 1,
    daily_limit           INT NOT NULL DEFAULT 0,
    available_from_hour   INT,
    available_to_hour     INT,
    overload_risk         VARCHAR(40) NOT NULL DEFAULT 'normal',
    last_seen_at          TIMESTAMP,
    updated_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_provider_capability_profile UNIQUE (guild_id, provider_user_id)
);
CREATE INDEX idx_provider_capability_guild_state ON provider_capability_profile(guild_id, provider_state);

CREATE TABLE knowledge_space (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id       BIGINT NOT NULL,
    channel_id     BIGINT,
    channel_ai_id  BIGINT,
    display_name   VARCHAR(120) NOT NULL,
    status         VARCHAR(40) NOT NULL DEFAULT 'draft',
    source_count   INT NOT NULL DEFAULT 0,
    chunk_count    INT NOT NULL DEFAULT 0,
    embedding_model VARCHAR(120),
    index_name     VARCHAR(160),
    created_by     BIGINT,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
